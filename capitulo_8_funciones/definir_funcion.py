# Aquí tenemos una función sencilla, llamada great_user(), que imprime un saludo
# Se usa la palabra clave def para definir un función, a continuación va el nombre
# de la función con unos parentesis, donde si hace falta se situa información para que 
# la función realize su trabajo. En este caso no hace falta por lo que los parentesis
# quedan vacios, pero es necesario ponerlos. Por último la definición termina con dos 
# puntos. Las líneas que aparecen abajo, conforman el cuerpo de la función, El texto
# de la segunda línea es un comentario conocido como 'cadena de documentación' que 
# describe lo que hace la función. Por lo general estas cadenas van en triples comillas
# Para llamar a la función escribimos su nombre seguido de los parentesis con la información
# necesaria si la función la necesitara.

def great_user():
    """Muestra un simple saludo."""
    print("Hello")

# Ahora llamamos a la función:

great_user()

